from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Protocol, Sequence, TYPE_CHECKING

if TYPE_CHECKING:
    import tkinter


@dataclass(frozen=True)
class KeySend:
    kind: str
    values: tuple[int, ...]
    key: str


ResolveLayoutScanCode = Callable[[str], int | None] | None


class KeyboardBackend(Protocol):
    """キーボードのフックと送信。

    フックの契約（どの OS の実装も守る）:
    - callback はフックのスレッドで呼ばれる。UI の操作は呼び出し側がディスパッチャ経由で行う。
    - callback へ渡すイベントは次の属性を持つ:
      `event_type`（"down" / "up"）・`scan_code`（int）・`name`（str | None）・`is_keypad`（bool）。
    - `suppress=True` のとき callback は bool を返す。True なら素通し、False なら抑止する。
      None は抑止として扱われる（Windows の keyboard ライブラリの挙動）ので返さない。
      `suppress=False` では戻り値を見ない。
    - 戻り値の handle は `unregister_hook` へ渡す以外に使わない。
    """

    def register_global_hook(
        self, callback: Callable[[object], bool | None], *, suppress: bool = False
    ) -> object: ...
    def register_key_hook(
        self, key: str, callback: Callable[[object], None], *, suppress: bool
    ) -> object:
        """`key` の押下（"down"）だけを callback へ渡す。`suppress=True` ならそのキーの押下・解放とも抑止する。"""
        ...
    def unregister_hook(self, handle: object) -> None: ...
    def resolve_send(self, key: str, resolve_layout_scan_code: ResolveLayoutScanCode) -> KeySend: ...
    def press_send(self, send: KeySend) -> None: ...
    def release_send(self, send: KeySend) -> None: ...
    def identity_of(self, send: KeySend) -> tuple[int, bool]: ...
    def needs_shift(self, send: KeySend) -> bool: ...
    def press_shift(self) -> None: ...
    def release_shift(self) -> None: ...
    def send_native_hotkey(
        self, hotkey: str, keys: Sequence[str], resolve_layout_scan_code: ResolveLayoutScanCode
    ) -> bool: ...
    def write_text(self, text: str) -> None: ...
    def repeat_timing(self) -> tuple[int, int]: ...


class MouseBackend(Protocol):
    def capture_next_click(self, on_capture: Callable[[float, float], None]) -> None: ...
    def cursor_position(self) -> tuple[int, int]: ...
    def move_cursor(self, x: int, y: int) -> None: ...
    def scroll_mouse(
        self, *, vertical: bool, deltas: Sequence[int], position: tuple[int, int] | None
    ) -> None: ...
    def click_at(self, x: int, y: int, button: str) -> None: ...
    def click_mouse(self, x: int, y: int, button: str, clicks: int) -> None: ...
    def mouse_down(self, button: str, x: int | None = None, y: int | None = None) -> None: ...
    def mouse_up(self, button: str, x: int | None = None, y: int | None = None) -> None: ...
    def drag_mouse(
        self, x: int, y: int, to_x: int, to_y: int, button: str, duration_sec: float
    ) -> None: ...


class ImeBackend(Protocol):
    def disable_for_text(self) -> object | None: ...
    def restore_after_text(self, reservation: object | None, character_count: int) -> None: ...
    def restore_ime_now(self) -> None: ...
    def get_own_open_status(self, window: tkinter.Misc) -> bool | None: ...
    def set_own_open_status(self, window: tkinter.Misc, is_open: bool) -> bool: ...


class WindowBackend(Protocol):
    def is_own_process_foreground(self) -> bool: ...
    def foreground_own_window(self) -> object | None: ...
    def window_handle(self, window: tkinter.Misc) -> object: ...
    def place_window_below(self, window: tkinter.Misc, above: object) -> bool: ...
    def list_monitor_rects(self) -> list[tuple[tuple[int, int, int, int], bool]]: ...
    def make_click_through_overlay(self, window: tkinter.Misc) -> bool: ...
    def is_mouse_button_down(self) -> bool: ...
    def is_shift_down(self) -> bool: ...
    def is_ctrl_alt_win_down(self) -> bool: ...


class TkKeyTranslator(Protocol):
    def numpad_name(self, keycode: object, state: object) -> str: ...
    def vk_to_scan_code(self, vk: int) -> int | None: ...
    def vk_to_char(self, vk: int) -> str: ...


class AppIdentity(Protocol):
    def apply_process_identity(self, app_id: str) -> bool: ...
    def relaunch(self, startup_cwd: str) -> OSError | None: ...


@dataclass(frozen=True)
class Capabilities:
    click_through_window: bool
    window_stacking: bool
    status_icon: bool
    ime_control: bool


@dataclass(frozen=True)
class OsBackend:
    capabilities: Capabilities
    ime: ImeBackend
    window: WindowBackend
    tk_keys: TkKeyTranslator
    app: AppIdentity
    keyboard: KeyboardBackend
    mouse: MouseBackend
